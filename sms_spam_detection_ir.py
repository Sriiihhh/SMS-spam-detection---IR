import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import time

from sklearn.model_selection import train_test_split
from sklearn.feature_extraction.text import TfidfVectorizer

from sklearn.tree import DecisionTreeClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.svm import LinearSVC
from sklearn.naive_bayes import MultinomialNB

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix,
    ConfusionMatrixDisplay
)

print("All libraries imported successfully!")

from google.colab import files

uploaded = files.upload()

import io

filename = next(iter(uploaded))

df = pd.read_csv(
    io.BytesIO(uploaded[filename]),
    encoding="latin-1"
)

print("Dataset loaded successfully!")
print("Dataset shape:", df.shape)

print("\nColumn names:")
print(df.columns.tolist())

print("\nFirst five rows:")
display(df.head())

df = df[["v1", "v2"]].copy()

df.columns = ["label", "text"]

print("Selected columns:")
print(df.head())

print("Missing values before cleaning:")
print(df.isnull().sum())

print("\nDuplicate rows before cleaning:", df.duplicated().sum())

df = df.dropna(subset=["label", "text"])

df["label"] = df["label"].astype(str).str.strip().str.lower()
df["text"] = df["text"].astype(str).str.strip()

df = df[
    (df["text"] != "") &
    (df["label"].isin(["ham", "spam"]))
]

df = df.drop_duplicates(
    subset=["label", "text"]
).reset_index(drop=True)

print("\nDataset shape after cleaning:", df.shape)

print("\nMissing values after cleaning:")
print(df.isnull().sum())

print("\nRemaining duplicate rows:", df.duplicated().sum())

print("Total number of messages:", len(df))

print("\nNumber of classes:", df["label"].nunique())

print("\nClass labels:")
print(df["label"].unique())

print("\nClass distribution:")
print(df["label"].value_counts())

print("\nPercentage distribution:")
print(
    (df["label"].value_counts(normalize=True) * 100)
    .round(2)
)

label_counts = df["label"].value_counts()

plt.figure(figsize=(7, 5))

label_counts.plot(kind="bar")

plt.title("Distribution of Ham and Spam Messages")
plt.xlabel("Message Category")
plt.ylabel("Number of Messages")
plt.xticks(rotation=0)

plt.tight_layout()
plt.show()

df["label_num"] = df["label"].map({
    "ham": 0,
    "spam": 1
})

print(df[["label", "label_num"]].head())

X = df["text"]
y = df["label_num"]

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training messages:", len(X_train))
print("Testing messages:", len(X_test))

print("\nTraining label distribution:")
print(y_train.value_counts())

print("\nTesting label distribution:")
print(y_test.value_counts())

tfidf = TfidfVectorizer(
    lowercase=True,
    stop_words="english",
    max_features=5000,
    ngram_range=(1, 2)
)

X_train_tfidf = tfidf.fit_transform(X_train)

X_test_tfidf = tfidf.transform(X_test)

print("Training feature shape:", X_train_tfidf.shape)
print("Testing feature shape:", X_test_tfidf.shape)

print("Number of vocabulary features:", len(tfidf.vocabulary_))

models = {
    "Decision Tree": DecisionTreeClassifier(
        random_state=42
    ),

    "KNN": KNeighborsClassifier(
        n_neighbors=5,
        metric="cosine",
        algorithm="brute"
    ),

    "SVM": LinearSVC(
        random_state=42,
        max_iter=5000
    ),

    "Naive Bayes": MultinomialNB()
}

print("All four classifiers are ready!")

results = []

trained_models = {}
predictions = {}

for name, model in models.items():

    print("\nTraining:", name)

    # Measure training time
    start_time = time.perf_counter()

    model.fit(X_train_tfidf, y_train)

    training_time = time.perf_counter() - start_time

    # Measure prediction time
    start_time = time.perf_counter()

    y_pred = model.predict(X_test_tfidf)

    prediction_time = time.perf_counter() - start_time

    # Evaluation metrics
    accuracy = accuracy_score(y_test, y_pred)

    precision = precision_score(
        y_test,
        y_pred,
        pos_label=1,
        zero_division=0
    )

    recall = recall_score(
        y_test,
        y_pred,
        pos_label=1,
        zero_division=0
    )

    f1 = f1_score(
        y_test,
        y_pred,
        pos_label=1,
        zero_division=0
    )

    results.append({
        "Model": name,
        "Accuracy": accuracy,
        "Spam Precision": precision,
        "Spam Recall": recall,
        "Spam F1-Score": f1,
        "Training Time (s)": training_time,
        "Prediction Time (s)": prediction_time
    })

    trained_models[name] = model
    predictions[name] = y_pred

    print("Accuracy:", round(accuracy, 4))
    print("Spam Precision:", round(precision, 4))
    print("Spam Recall:", round(recall, 4))
    print("Spam F1-Score:", round(f1, 4))
    print("Training time:", round(training_time, 4), "seconds")
    print("Prediction time:", round(prediction_time, 4), "seconds")


results_df = pd.DataFrame(results)

print("\nFINAL MODEL COMPARISON")

display(
    results_df.sort_values(
        by="Spam F1-Score",
        ascending=False
    ).reset_index(drop=True)
)

metrics = [
    "Accuracy",
    "Spam Precision",
    "Spam Recall",
    "Spam F1-Score"
]

results_df.set_index("Model")[metrics].plot(
    kind="bar",
    figsize=(12, 6)
)

plt.title("Performance Comparison of Spam Classification Algorithms")
plt.xlabel("Classification Algorithm")
plt.ylabel("Score")
plt.ylim(0, 1.05)
plt.xticks(rotation=0)
plt.legend(loc="lower right")

plt.tight_layout()
plt.show()

plt.figure(figsize=(9, 5))

plt.bar(
    results_df["Model"],
    results_df["Training Time (s)"]
)

plt.title("Training Time Comparison")
plt.xlabel("Classification Algorithm")
plt.ylabel("Training Time (seconds)")
plt.xticks(rotation=15)

plt.tight_layout()
plt.show()

best_index = results_df["Spam F1-Score"].idxmax()

best_model_name = results_df.loc[
    best_index, "Model"
]

best_predictions = predictions[best_model_name]

print("Best model by spam F1-score:", best_model_name)

print("\nClassification Report:")

print(
    classification_report(
        y_test,
        best_predictions,
        labels=[0, 1],
        target_names=["Ham", "Spam"],
        zero_division=0
    )
)

cm = confusion_matrix(
    y_test,
    best_predictions,
    labels=[0, 1]
)

disp = ConfusionMatrixDisplay(
    confusion_matrix=cm,
    display_labels=["Ham", "Spam"]
)

fig, ax = plt.subplots(figsize=(7, 6))

disp.plot(
    ax=ax,
    cmap="Blues",
    values_format="d"
)

plt.title(
    f"Confusion Matrix - {best_model_name}"
)

plt.tight_layout()
plt.show()

k_values = [3, 5, 7, 9]

knn_results = []

for k in k_values:

    print("Testing K =", k)

    model = KNeighborsClassifier(
        n_neighbors=k,
        metric="cosine",
        algorithm="brute"
    )

    start_time = time.perf_counter()

    model.fit(X_train_tfidf, y_train)

    training_time = time.perf_counter() - start_time

    y_pred = model.predict(X_test_tfidf)

    accuracy = accuracy_score(y_test, y_pred)

    precision = precision_score(
        y_test,
        y_pred,
        pos_label=1,
        zero_division=0
    )

    recall = recall_score(
        y_test,
        y_pred,
        pos_label=1,
        zero_division=0
    )

    f1 = f1_score(
        y_test,
        y_pred,
        pos_label=1,
        zero_division=0
    )

    knn_results.append({
        "K": k,
        "Accuracy": accuracy,
        "Spam Precision": precision,
        "Spam Recall": recall,
        "Spam F1-Score": f1,
        "Training Time (s)": training_time
    })

knn_df = pd.DataFrame(knn_results)

print("\nKNN WHAT-IF EXPERIMENT RESULTS")

